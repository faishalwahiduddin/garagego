/// Unit symbols and separators used to compose measurements.
///
/// These are not translatable words: `km`, `L` and the arithmetic signs read the
/// same in every supported locale. Keeping them named lets the UI compose
/// strings without hiding literals in widget code.
const kKmUnit = 'km';
const kLiterUnit = 'L';
const kPlusSign = '+';
const kPerKmSuffix = '/km';
const kPercentSign = '%';
const kSpaceChar = ' ';
const kMidlineSpace = ' — ';
